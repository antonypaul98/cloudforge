"""Opt-in, real-loopback fixture observation attached to real manifest review.

This runs an ephemeral, owned CI/demo HTTP fixture, not the user's application.
It never deploys application code, accesses external services or authenticates
a reviewer. All approval objects are explicitly synthetic fixture inputs.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
import sys
from threading import Thread

from .application_demo import _load_selected_manifests, review_application_manifests
from .deployment import (
    DeploymentApproval, authorize_deployment_handoff, prepare_deployment_request,
)
from .iac import render_iac_proposal
from .inspector import inspect_application
from .local_adapter import (
    LocalExecutionApproval, authorize_local_execution, prepare_local_execution_request,
)
from .observation_http import LoopbackHTTPProbeTarget, collect_loopback_http_samples
from .observation_plan import ObservationProbe, prepare_observation_plan
from .planner import derive_requirements


def run_loopback_observation_demo(
    name: str, manifests: dict[str, str], target_id: str, *,
    allow_fixture: bool = False,
) -> dict[str, object]:
    """Observe actual HEAD results on a temporary loopback-only test fixture.

    No caller-provided host, port, path, script, executable, or provider is used.
    The fixture is NOT the reviewed application; the local-only approvals are
    generated by this demo and do not authenticate a human.
    """
    if allow_fixture is not True:
        raise ValueError("explicit loopback fixture opt-in is required")
    review = review_application_manifests(name, manifests, target_id)
    inspected = inspect_application(name, manifests)
    plan = derive_requirements(inspected.profile)
    proposal = render_iac_proposal(plan)
    request = prepare_deployment_request(plan, proposal, target_id)
    if request.digest != review["handoff_request"]["request_digest"]:
        raise ValueError("review and handoff provenance differ")

    # A canonical manifest fingerprint packet, not runnable application bytes.
    artifact = json.dumps(
        review["source_review_binding"],
        sort_keys=True, separators=(",", ":"), ensure_ascii=True,
        allow_nan=False,
    ).encode("ascii")
    handoff = authorize_deployment_handoff(
        plan, proposal, request,
        DeploymentApproval(request.digest, "synthetic-fixture-reviewer"),
    )
    local_request = prepare_local_execution_request(handoff, artifact)
    local_approval = LocalExecutionApproval(
        local_request.digest, "synthetic-fixture-reviewer",
    )
    receipt = authorize_local_execution(
        handoff, artifact, local_request, local_approval,
    )
    observation_plan = prepare_observation_plan(
        handoff, artifact, local_approval, receipt,
        (ObservationProbe("readiness", 5, 2, 1),
         ObservationProbe("liveness", 5, 2, 1)),
    )

    state = {"status": 204}

    class OwnedFixtureHandler(BaseHTTPRequestHandler):
        def do_HEAD(self):
            if self.path != "/health":
                self.send_response(404)
            else:
                self.send_response(state["status"])
            self.send_header("Content-Length", "0")
            self.end_headers()

        def do_GET(self):
            self.send_response(405)
            self.end_headers()

        def log_message(self, *_args):
            pass

    # Binding an ephemeral numeric loopback port never contacts a real service.
    server = ThreadingHTTPServer(("127.0.0.1", 0), OwnedFixtureHandler)
    server.daemon_threads = True
    thread = Thread(target=server.serve_forever, daemon=True)
    trace: list[dict[str, object]] = []
    try:
        thread.start()
        targets = (
            LoopbackHTTPProbeTarget("readiness", "127.0.0.1", server.server_port, "/health"),
            LoopbackHTTPProbeTarget("liveness", "127.0.0.1", server.server_port, "/health"),
        )
        for phase, status, expected in (
            ("initial", 204, "pass"),
            ("fixture-failure", 503, "fail"),
            ("fixture-restored", 204, "pass"),
        ):
            state["status"] = status
            samples = collect_loopback_http_samples(
                handoff, artifact, local_approval, receipt,
                observation_plan, targets, allowed_targets=targets,
            )
            if len(samples) != 2 or any(s.outcome != expected for s in samples):
                raise RuntimeError("owned fixture did not exhibit expected HEAD behavior")
            # No nondeterministic ports, timing, or raw source text in output.
            trace.append({
                "phase": phase,
                "samples": [{"kind": s.kind, "outcome": s.outcome} for s in samples],
            })
    finally:
        server.shutdown()
        thread.join(timeout=5)
        server.server_close()
    if thread.is_alive():
        raise RuntimeError("owned fixture server failed to stop")

    return {
        "demo_only": True,
        "application": name,
        "target_id": target_id,
        "source_review_binding_digest": review["source_review_binding"]["digest"],
        "handoff_request_digest": request.digest,
        "fixture_observation": trace,
        "fixture_server_stopped": True,
        "fixture_behavior_observed": True,
        "fixture_fault_injected": True,
        "authenticated_review": False,
        "application_executed": False,
        "deployment_observed": False,
        "recovery_performed": False,
        "infrastructure_mutated": False,
        "limitations": [
            "The observed HTTP server is an owned loopback fixture, not the reviewed app.",
            "All reviewer identities and approvals are synthetic and not authenticated.",
            "No real app deployment, infrastructure observation or recovery was performed.",
        ],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Opt-in real HEAD checks against an owned loopback demo fixture",
    )
    parser.add_argument("--name", required=True)
    parser.add_argument("--target", required=True)
    parser.add_argument("--manifest", action="append", required=True)
    parser.add_argument("--allow-loopback-fixture", action="store_true")
    args = parser.parse_args(argv)
    try:
        payload = run_loopback_observation_demo(
            args.name, _load_selected_manifests(args.manifest), args.target,
            allow_fixture=args.allow_loopback_fixture,
        )
    except (ValueError, RuntimeError) as exc:
        parser.error(str(exc))
    sys.stdout.write(json.dumps(payload, sort_keys=True, indent=2, ensure_ascii=True) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
